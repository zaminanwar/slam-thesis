def get_param_space(algorithm: str) -> dict:
    """Get the parameter space for a given algorithm."""
    if algorithm == 'slam_toolbox':
        return SLAM_TOOLBOX_PARAM_SPACE
    elif algorithm == 'cartographer':
        return CARTOGRAPHER_PARAM_SPACE
    else:
        raise ValueError(f"Unknown algorithm: {algorithm}")


def generate_config(algorithm: str, params: dict[str, Any], output_path: Path) -> None:
    """Generate config file for the given algorithm."""
    if algorithm == 'slam_toolbox':
        generate_slam_toolbox_config(params, output_path)
    elif algorithm == 'cartographer':
        generate_cartographer_config(params, output_path)
    else:
        raise ValueError(f"Unknown algorithm: {algorithm}")


